export async function generateMetadata(): Promise<Metadata> {
  const cfg = getSiteConfig();
  const svc = TH_SERVICE[cfg.focus];
  const nearMe = TH_NEAR_ME[cfg.focus];
  const title = nearMe
    ? `${nearMe} ในกรุงเทพฯ — รีวิวจริง เช็คราคา`
    : svc
      ? `คลินิก${svc}ในกรุงเทพฯ — รีวิวจริง เช็คราคา`
      : "คลินิกในกรุงเทพ — รีวิวที่ตรวจสอบแล้วและคะแนนความน่าเชื่อถือ";
  const description =
    TH_DESC[cfg.focus] ??
    (svc
      ? `ไดเรกทอรีคลินิก${svc}ในกรุงเทพฯ จัดอันดับด้วยคะแนนความน่าเชื่อถือจากรีวิว Google จริง`
      : "ไดเรกทอรีคลินิกความงามและการแพทย์ในกรุงเทพ จัดอันดับด้วยคะแนนความน่าเชื่อถือจากรีวิว Google จริง");
  return {
    title,
    description,
    // hreflang 클러스터는 세 페이지가 서로를 전부 선언해야 자기확인이 된다.
    // 예전엔 / 는 bare code(en/th/ko), /th 는 region code 2개, /ko 는 3개로
    // 제각각이라 클러스터가 성립하지 않았다 (2026-08-06 감사).
    alternates: {
      canonical: "/th",
      languages: { en: "/", th: "/th", ko: "/ko", "x-default": "/" },
    },
    // 2026-09-02: siteName 은 페이지마다 다시 넣어야 한다 — Next 는 openGraph 를
    // 객체 단위로 교체해서, 루트 layout 에 있어도 페이지가 정의하면 사라진다.
    openGraph: { siteName: cfg.brand, title, description, locale: "th_TH" },
  };
}

