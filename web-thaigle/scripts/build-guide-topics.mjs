// Regenerates lib/guideTopics.ts + lib/guideTopicLoaders.ts from the
// standalone Bangkok topic components in components/.
//
// Background: /guide used to render ~253 of these blocks inline, producing a
// 6.5 MB HTML document. Each block is a self-contained topic (visas, ATMs,
// Songkran, temples, …) that deserves its own URL, so they're now served from
// /guide/bangkok/{slug}. This script keeps that registry in sync.
//
// Usage:  node scripts/build-guide-topics.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const COMPONENTS = path.join(ROOT, "components");

// A topic block is a component that (a) lives in components/Bangkok*.tsx,
// (b) exposes the uniform "uppercase tracking-widest" banner that carries its
// title, and (c) is not already rendered on some other page (those stay inline
// where they are — moving them would strip content from pages that rely on it).
const INLINE_ELSEWHERE = new Set(
  fs
    .readdirSync(path.join(ROOT, "app"), { recursive: true })
    .filter((f) => typeof f === "string" && f.endsWith(".tsx") && f !== path.join("guide", "page.tsx"))
    .flatMap((f) => {
      const src = fs.readFileSync(path.join(ROOT, "app", f), "utf8");
      return [...src.matchAll(/<(Bangkok[A-Za-z0-9]*)\b/g)].map((m) => m[1]);
    })
);

const BANNER = /uppercase tracking-widest[^>]*>\s*\n?\s*([^<>{}\n][^<>{}]*?)\s*\n?\s*<\//;
const EMOJI_PREFIX = /^([\p{Extended_Pictographic}‍️]+)\s*/u;

function kebab(name) {
  return name
    .replace(/^Bangkok/, "Bangkok ")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const rows = [];
const seen = new Map();

for (const file of fs.readdirSync(COMPONENTS).sort()) {
  if (!file.startsWith("Bangkok") || !file.endsWith(".tsx")) continue;
  const component = file.replace(/\.tsx$/, "");
  if (INLINE_ELSEWHERE.has(component)) continue;

  const src = fs.readFileSync(path.join(COMPONENTS, file), "utf8");
  if (!src.includes(`export function ${component}(`)) continue;

  const banner = src.match(BANNER);
  if (!banner) continue;
  const raw = banner[1].trim().replace(/\s+/g, " ");
  if (raw.length < 9) continue;

  const emojiMatch = raw.match(EMOJI_PREFIX);
  const emoji = emojiMatch ? emojiMatch[1] : "📌";
  const title = raw.replace(EMOJI_PREFIX, "").trim();

  const slug = kebab(component);
  if (seen.has(slug)) throw new Error(`slug collision: ${slug} (${component} vs ${seen.get(slug)})`);
  seen.set(slug, component);

  // First data-entry `name:` reads as a natural one-line summary of the block.
  const lead = src.match(/name:\s*"([^"]{20,220})"/);
  rows.push({ slug, component, emoji, title, lead: lead ? lead[1] : "" });
}

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

const registry = `// AUTO-GENERATED by scripts/build-guide-topics.mjs — do not edit by hand.
//
// These blocks used to all render on /guide at once, producing a 6.5 MB HTML
// document: unusable on mobile, and ${rows.length} distinct topics competing for
// relevance on one URL. Each now has its own page at /guide/bangkok/{slug}.

export type GuideTopic = {
  slug: string;
  /** Export name in components/{component}.tsx */
  component: string;
  emoji: string;
  title: string;
  lead: string;
};

export const GUIDE_TOPICS: GuideTopic[] = [
${rows.map((r) => `  { slug: "${r.slug}", component: "${r.component}", emoji: "${r.emoji}", title: "${esc(r.title)}", lead: "${esc(r.lead)}" },`).join("\n")}
];

const BY_SLUG = new Map(GUIDE_TOPICS.map((t) => [t.slug, t]));

export function findGuideTopic(slug: string): GuideTopic | undefined {
  return BY_SLUG.get(slug);
}
`;

// import() needs a literal specifier to be statically analysable, so the
// loader map is generated rather than built from the slug at runtime. Each
// entry stays its own chunk, so a topic page pulls in only its own block.
const loaders = `// AUTO-GENERATED by scripts/build-guide-topics.mjs — do not edit by hand.
import type { ComponentType } from "react";

export const GUIDE_TOPIC_LOADERS: Record<string, () => Promise<ComponentType>> = {
${rows
  .map(
    (r) =>
      `  "${r.slug}": () => import("@/components/${r.component}").then((m) => m.${r.component} as ComponentType),`
  )
  .join("\n")}
};
`;

fs.writeFileSync(path.join(ROOT, "lib", "guideTopics.ts"), registry);
fs.writeFileSync(path.join(ROOT, "lib", "guideTopicLoaders.ts"), loaders);
console.log(`wrote ${rows.length} topics → lib/guideTopics.ts + lib/guideTopicLoaders.ts`);
