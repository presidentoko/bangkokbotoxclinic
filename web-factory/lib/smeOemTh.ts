const MFG =
  /manufactur|factory|ผู้ผลิต|โรงงาน|รับผลิต|\boem\b|\bodm\b|producer|processing|แปรรูป|co-pack|โรงพิมพ์|printing company|commercial printer|screen print|สกรีน|roaster|โรงคั่ว|industry|อุตสาหกรรม/;

const STOREFRONT =
  /restaurant|ร้านอาหาร|hotel|โรงแรม|\bcafe\b|คาเฟ่|coffee shop|ร้านกาแฟ|supermarket|convenience|tailor|ร้านตัดเสื้อ|sign shop|ร้านป้าย|bakery|เบเกอรี่|candy store|cosmetics store|vitamin & supplements store/;

function haystack(r: Supplier): { cats: string; all: string } {
  const cats = [r.primary_type || "", ...(r.raw_categories || [])].join(" | ").toLowerCase();
  return { cats, all: `${cats} | ${(r.name || "").toLowerCase()}` };
}

export function matchesSmeOem(v: SmeOemTh, r: Supplier): boolean {
  const { cats, all } = haystack(r);
  if (!v.product.test(all) || !MFG.test(all)) return false;
  // 소매점 카테고리라도 이름에 รับผลิต/โรงงาน 이 있으면 실제 공장인 경우가 많다
  // (예: "Life by NK OEM Factory" 의 업종이 "Vitamin & supplements store").
  if (STOREFRONT.test(cats) && !/รับผลิต|โรงงาน|\boem\b|factory/.test((r.name || "").toLowerCase())) return false;
  return true;
}

