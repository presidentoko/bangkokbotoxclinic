export function smeOemSuppliers(v: SmeOemTh, suppliers: Supplier[]): Supplier[] {
  return suppliers.filter((r) => matchesSmeOem(v, r)).sort((a, b) => b.trust_score - a.trust_score);
}

/** 공급사가 MIN_TH_OEM 곳 이상인 품목만 — 페이지 생성·허브·사이트맵 공용. */
export function liveSmeOem(suppliers: Supplier[]): { v: SmeOemTh; count: number }[] {
  return SME_OEM_TH.map((v) => ({ v, count: smeOemSuppliers(v, suppliers).length })).filter(
    (x) => x.count >= MIN_TH_OEM,
  );
}

export function findSmeOem(slug: string): SmeOemTh | undefined {
  return SME_OEM_TH.find((v) => v.slug === slug);
}
